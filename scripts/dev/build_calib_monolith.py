"""从 src/calib_core 生成单文件 subtitle_calib_merged.py。

生成物必须兼容：
  · 旧客户端整文件同步（calib_merge_core 的 AST 字面量表/ENTITIES 合并）；
  · standalone/kb_admin.py 的 ast.literal_eval 读表；
  · 现有 subprocess / importlib 消费者。

用法：
    tools\\python\\python.exe scripts\\dev\\build_calib_monolith.py --out data\\tmp\\calib_monolith_candidate.py
    tools\\python\\python.exe scripts\\dev\\build_calib_monolith.py --check
    tools\\python\\python.exe scripts\\dev\\build_calib_monolith.py --baseline data\\backup\\old.py --out data\\tmp\\c.py
"""
import argparse
import ast
import hashlib
import importlib
import importlib.util
import os
import re
import sys
import tempfile

ROOT = os.getcwd()
if not os.path.isfile(os.path.join(ROOT, "subtitle_calib_merged.py")):
    ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "src")
if SRC not in sys.path:
    sys.path.insert(0, SRC)
os.environ.setdefault("VT_NO_SYNC", "1")

DATA_FILES = [
    # ko 依赖 ark 的 _SEONJEONG_ANCHOR，顺序不能按字母排
    "bilingual", "ja", "ark", "ko", "endfield", "misc", "limbus", "modes",
]
LOGIC_FILES = [
    "text", "replace", "asr", "state", "engine", "modes", "srt",
    "format", "inspect", "kb", "learn", "sync", "cli",
]


def read_version():
    p = os.path.join(ROOT, "src", "video_toolbox_qt.py")
    try:
        m = re.search(r'VERSION\s*=\s*"([\d.]+)"', open(p, encoding="utf-8").read())
        return m.group(1) if m else "2.7.0"
    except OSError:
        return "2.7.0"


def strip_module(path):
    """去掉模块头、模块 docstring、所有相对 import；保留注释/函数体。"""
    text = open(path, encoding="utf-8").read()
    tree = ast.parse(text)
    lines = text.splitlines()
    remove = set()
    for i, line in enumerate(lines[:3], 1):
        if line.startswith("# -*- coding") or line.startswith("# @version"):
            remove.add(i)
    if (tree.body and isinstance(tree.body[0], ast.Expr)
            and isinstance(tree.body[0].value, ast.Constant)
            and isinstance(tree.body[0].value.value, str)):
        remove.update(range(tree.body[0].lineno, tree.body[0].end_lineno + 1))
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and (node.level or 0) > 0:
            remove.update(range(node.lineno, node.end_lineno + 1))
    out = [line for i, line in enumerate(lines, 1) if i not in remove]
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


def entity_line(e):
    return (
        f"    Entity({e.canonical!r}, modes={e.modes!r}, en={e.en!r}, "
        f"ja={e.ja!r}, ko={e.ko!r}, category={e.category!r}, "
        f"variants={e.variants!r}, ctx={e.ctx!r}, exclude={e.exclude!r}, "
        f"note={e.note!r}),"
    )


def build_text(pkg, version):
    parts = [
        "# -*- coding: utf-8 -*-",
        f"# @version {version}",
        "# GENERATED by scripts/dev/build_calib_monolith.py from src/calib_core.",
        "# DO NOT EDIT. 修改 src/calib_core 后重新生成。",
        "",
        "USAGE_DOC = " + repr(pkg.USAGE_DOC),
        "__doc__ = USAGE_DOC",
        "",
    ]
    for name in DATA_FILES:
        parts.append(f"# ===== data/{name}.py =====")
        parts.append(strip_module(os.path.join(SRC, "calib_core", "data", name + ".py")))
        parts.append("")
    parts.append("# ===== data/entities_base.py =====")
    parts.append(strip_module(os.path.join(SRC, "calib_core", "data", "entities_base.py")))
    parts.append("")
    parts.append("# ===== ENTITIES（从 calib_core.ENTITIES 序列化，兼容旧 merge core）=====")
    parts.append("ENTITIES = [")
    parts.extend(entity_line(e) for e in pkg.ENTITIES)
    parts.append("]")
    parts.append("")
    for name in LOGIC_FILES:
        parts.append(f"# ===== {name}.py =====")
        parts.append(strip_module(os.path.join(SRC, "calib_core", name + ".py")))
        parts.append("")
    parts.append('if __name__ == "__main__":\n    main_argv()')
    text = "\n".join(parts).rstrip() + "\n"
    tree = ast.parse(text)
    bad = [n for n in ast.walk(tree)
           if isinstance(n, ast.ImportFrom) and (n.level or 0) > 0]
    if bad:
        raise SystemExit(f"生成物仍含相对 import: {bad[:3]}")
    return text


def to_crlf(text):
    return text.replace("\n", "\r\n")


def write_text(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    data = to_crlf(text).encode("utf-8")
    with open(path, "wb") as f:
        f.write(data)
    return data


def load_module(path, name="calib_monolith_check"):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def check_runtime(path, pkg):
    cand = load_module(path)
    errors = []
    for attr in ("BILINGUAL_TERMS", "CONTEXT_MAP", "EXCLUDE_CONTEXT",
                 "WORD_MAP", "EN_LINE_TERM_FIXES"):
        if getattr(cand, attr, None) != getattr(pkg, attr, None):
            errors.append(attr)
    if len(cand.ENTITIES) != len(pkg.ENTITIES):
        errors.append(f"ENTITIES {len(cand.ENTITIES)}/{len(pkg.ENTITIES)}")
    if cand.__doc__ != pkg.USAGE_DOC:
        errors.append("__doc__")
    if not callable(getattr(cand, "process", None)):
        errors.append("process")
    return errors


def ast_compat(text):
    """检查旧 merge/kb_admin 需要的字面量形态。"""
    tree = ast.parse(text)
    tables = {}
    entities = None
    for node in tree.body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
                and isinstance(node.value, (ast.Dict, ast.List))):
            tables[node.targets[0].id] = node.value
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
                and node.targets[0].id == "ENTITIES"
                and isinstance(node.value, ast.List)):
            entities = node.value
    required = {
        "BILINGUAL_TERMS", "CONTEXT_MAP", "EXCLUDE_CONTEXT", "WORD_MAP",
        "EN_LINE_TERM_FIXES", "JA_TERMS", "JA_CONTEXT", "JA_ENDFIELD_TERMS",
        "JA_ENDFIELD_CONTEXT", "KO_TERMS", "KO_CONTEXT", "KO_ASR_TERMS",
        "KO_ASR_CONTEXT", "WWOC_TERMS", "WWOC_CONTEXT", "PGR_EN_TERMS", "ENDFIELD_TERMS",
        "ENDFIELD_BI_TERMS", "ENDFIELD_BI_CONTEXT", "ENDFIELD_KO_TERMS",
        "ENDFIELD_KO_CONTEXT", "AK_TERMS", "AK_CONTEXT", "AK_KO_TERMS",
        "AK_KO_CONTEXT", "ZH_ONLY_TERMS", "REACT_TERMS", "REACT_CONTEXT",
        "HSR_TERMS", "HSR_CONTEXT", "POKEMON_TERMS", "POKEMON_CONTEXT",
        "ZELDA_TERMS", "EN_ASR_SPLIT_FIXES", "_MODE_TERM_TABLE",
        "_MODE_CTX_TABLE", "LIMBUS_TERMS", "LIMBUS_CONTEXT",
    }
    missing = sorted(required - set(tables))
    if entities is None:
        return ["ENTITIES 不是字面量 List"], 0
    if not entities.elts:
        return ["ENTITIES 为空"], 0
    if not all(isinstance(e, ast.Call) for e in entities.elts):
        return ["ENTITIES 含非 Entity(...) 元素"], 0
    return missing, len(entities.elts)


def merge_compat(old_path, text):
    sys.path.insert(0, SRC)
    import calib_merge_core as mc
    old = open(old_path, encoding="utf-8").read().replace("\r\n", "\n")
    merged, added, conflicts = mc.merge_calib_script(old, text, old)
    bad = [c for c in conflicts if "解析失败" in c]
    compile(merged, "<merged>", "exec")
    return added, conflicts, bool(bad)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="", help="候选输出路径；不传则只做检查")
    ap.add_argument("--check", action="store_true",
                    help="与当前根文件比较；不一致退出 1")
    ap.add_argument("--baseline", default="", help="旧 monolith 路径，做旧合并器兼容检查")
    ap.add_argument("--version", default="", help="覆盖版本号（默认读 video_toolbox_qt.py）")
    args = ap.parse_args()

    pkg = importlib.import_module("calib_core")
    version = args.version or read_version()
    text = build_text(pkg, version)

    if args.out:
        data = write_text(args.out, text)
        print(f"写入 {args.out}：{len(data)} bytes / {text.count(chr(10)) + 1} 行 / "
              f"sha256 {hashlib.sha256(data).hexdigest()[:16]}")

    missing, n_ent = ast_compat(text)
    if missing:
        raise SystemExit(f"缺少旧合并器需要的字面量表: {missing}")
    if n_ent != len(pkg.ENTITIES):
        raise SystemExit(f"ENTITIES 数量不一致: {n_ent}/{len(pkg.ENTITIES)}")
    print(f"AST 兼容：{n_ent} 个 Entity，字面量表齐全")

    if args.out:
        tmp = args.out
        errors = check_runtime(tmp, pkg)
        if errors:
            raise SystemExit(f"候选运行时自检失败: {errors}")
        print("候选运行时自检：表/ENTITIES/__doc__/process 通过")

    if args.baseline:
        added, conflicts, bad = merge_compat(args.baseline, text)
        print(f"旧合并器兼容：added={added} conflicts={len(conflicts)} 解析失败={bad}")
        if bad:
            raise SystemExit("旧合并器无法解析生成物")

    if args.check:
        target = args.out or os.path.join(ROOT, "subtitle_calib_merged.py")
        expected = to_crlf(text).encode("utf-8")
        actual = open(target, "rb").read() if os.path.isfile(target) else b""
        if actual == expected:
            print(f"CHECK OK：{target} 与生成结果一致")
        else:
            print(f"CHECK FAIL：{target} 与生成结果不一致（actual {len(actual)} B）")
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
